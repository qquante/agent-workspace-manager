package secrets

import (
	"bufio"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
)

const (
	WorkspaceManifestPath        = ".stola/secrets/manifest.json"
	ContainerSecretsEnvPath      = "/home/stola/.config/stola/secrets.env"
	ContainerSecretsManifestPath = "/home/stola/.config/stola/secrets.json"
	ContainerProfilePath         = "/home/stola/.profile"
)

type Secret struct {
	Name  string
	Value string
}

type Bundle struct {
	Secrets      []Secret
	AllowedNames []string
	Files        map[string][]byte
}

var envNamePattern = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)

func LoadProviderEnvFile(filePath string, allowedNames []string) (Bundle, error) {
	allSecrets, err := ParseEnvFile(filePath)
	if err != nil {
		return Bundle{}, err
	}
	allowed := map[string]bool{}
	for _, name := range allowedNames {
		if envNamePattern.MatchString(name) {
			allowed[name] = true
		}
	}
	var filtered []Secret
	for _, secret := range allSecrets {
		if allowed[secret.Name] {
			filtered = append(filtered, secret)
		}
	}
	if len(filtered) == 0 {
		return Bundle{}, errors.New("secret file has no variables matching the provider manifest")
	}
	sort.SliceStable(filtered, func(i, j int) bool { return filtered[i].Name < filtered[j].Name })
	manifest, err := renderManifest(filtered, allowedNames)
	if err != nil {
		return Bundle{}, err
	}
	envFile := renderShellEnv(filtered)
	return Bundle{
		Secrets:      filtered,
		AllowedNames: append([]string(nil), allowedNames...),
		Files: map[string][]byte{
			WorkspaceManifestPath:        manifest,
			ContainerSecretsManifestPath: manifest,
			ContainerSecretsEnvPath:      envFile,
		},
	}, nil
}

func ParseEnvFile(filePath string) ([]Secret, error) {
	file, err := os.Open(filePath)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	var out []Secret
	seen := map[string]bool{}
	scanner := bufio.NewScanner(file)
	lineNo := 0
	for scanner.Scan() {
		lineNo++
		line := scanner.Text()
		if lineNo == 1 {
			line = strings.TrimPrefix(line, "\ufeff")
		}
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		line = strings.TrimPrefix(line, "export ")
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			return nil, fmt.Errorf("line %d: expected KEY=VALUE", lineNo)
		}
		key = strings.TrimSpace(key)
		if !envNamePattern.MatchString(key) {
			return nil, fmt.Errorf("line %d: invalid environment variable name %q", lineNo, key)
		}
		if seen[key] {
			return nil, fmt.Errorf("line %d: duplicate environment variable %q", lineNo, key)
		}
		seen[key] = true
		value = strings.TrimSpace(value)
		value = unquote(value)
		if strings.ContainsRune(value, '\x00') {
			return nil, fmt.Errorf("line %d: secret value contains NUL byte", lineNo)
		}
		out = append(out, Secret{Name: key, Value: value})
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if len(out) == 0 {
		return nil, errors.New("secret file is empty")
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func Names(secrets []Secret) []string {
	out := make([]string, 0, len(secrets))
	for _, secret := range secrets {
		out = append(out, secret.Name)
	}
	sort.Strings(out)
	return out
}

func ValuesByName(secrets []Secret) map[string]string {
	out := make(map[string]string, len(secrets))
	for _, secret := range secrets {
		out[secret.Name] = secret.Value
	}
	return out
}

func WriteManifestToDir(bundle Bundle, workspaceDir string) error {
	content := bundle.Files[WorkspaceManifestPath]
	if len(content) == 0 {
		return errors.New("secret manifest is empty")
	}
	target := filepath.Join(workspaceDir, filepath.FromSlash(WorkspaceManifestPath))
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	return os.WriteFile(target, content, 0o600)
}

func renderManifest(items []Secret, allowedNames []string) ([]byte, error) {
	doc := struct {
		Version      int       `json:"version"`
		GeneratedAt  time.Time `json:"generated_at"`
		SecretNames  []string  `json:"secret_names"`
		AllowedNames []string  `json:"allowed_names,omitempty"`
	}{
		Version:      1,
		GeneratedAt:  time.Now().UTC(),
		SecretNames:  Names(items),
		AllowedNames: append([]string(nil), allowedNames...),
	}
	sort.Strings(doc.AllowedNames)
	return json.MarshalIndent(doc, "", "  ")
}

func renderShellEnv(items []Secret) []byte {
	lines := []string{
		"# Generated by Stola. Contains secrets. Do not commit or copy into /workspace.",
		"set -a",
	}
	for _, item := range items {
		lines = append(lines, fmt.Sprintf("%s=%s", item.Name, shellQuote(item.Value)))
	}
	lines = append(lines, "set +a", "")
	return []byte(strings.Join(lines, "\n"))
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\\''") + "'"
}

func unquote(value string) string {
	if len(value) >= 2 {
		if (value[0] == '"' && value[len(value)-1] == '"') || (value[0] == '\'' && value[len(value)-1] == '\'') {
			return value[1 : len(value)-1]
		}
	}
	return value
}
